"""Wave 4 regression tests for DD-A3: the three destructive
endpoints the wave 3 S5 fix did not cover - API key
generate/rotate, API key revoke, and backup restore-preimport -
now require the same explicit confirm=true.  /api/kill is the
safety stop and must stay one-click."""
import pytest
from fastapi.testclient import TestClient

from deskdora import server
from deskdora.apikey import ApiKeyStore

client = TestClient(server.app)


@pytest.fixture
def key_store(tmp_path, monkeypatch):
    store = ApiKeyStore(str(tmp_path / "api-key.json"))
    monkeypatch.setattr(server, "API_KEYS", store)
    return store


def test_key_generate_requires_confirmation(key_store):
    assert client.post(
        "/api/access/key/generate").status_code == 409
    # Nothing was generated by the refused call.
    assert key_store.status()["configured"] is False
    res = client.post("/api/access/key/generate?confirm=true")
    assert res.status_code == 200
    assert key_store.verify(res.json()["key"]) is True


def test_key_revoke_requires_confirmation(key_store):
    key = key_store.generate()
    assert client.post(
        "/api/access/key/revoke").status_code == 409
    # The refused revoke left the key working.
    assert key_store.verify(key) is True
    assert client.post(
        "/api/access/key/revoke?confirm=true").status_code == 200
    assert key_store.verify(key) is False


def test_restore_preimport_requires_confirmation(tmp_path,
                                                 monkeypatch):
    monkeypatch.setattr(server, "DATA_DIR", str(tmp_path))
    # Confirmation is checked first: without it the answer is
    # 409 even when there is no snapshot to restore.
    assert client.post(
        "/api/backup/restore-preimport").status_code == 409
    res = client.post("/api/backup/restore-preimport?confirm=true")
    assert res.status_code == 400
    assert "no pre-import backup" in res.json()["detail"]


def test_kill_stays_one_click():
    try:
        assert client.post("/api/kill").status_code == 200
    finally:
        server.MANAGER.kill.reset()
